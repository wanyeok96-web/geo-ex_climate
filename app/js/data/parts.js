const PAGES = [];
const PAGE_BY_ID = {};

(function buildPages() {
  function add(p) { p.index = PAGES.length; PAGES.push(p); PAGE_BY_ID[p.id] = p; }
  add({ id: "home", kind: "home", title: "수업 시작하기" });
  PARTS.forEach(function (part) {
    part.chapters.forEach(function (c, j) {
      const p = {
        id: c.id, part: part, chapter: c, first: j === 0,
        kind: part.is3d ? "atmos3d" : "chapter",
        title: c.title
      };
      if (part.is3d) {
        p.step = c.step;
        p.goal = ATMOS_GOALS[c.step];
      } else if (c.zone) {
        p.zone = c.zone;
        p.goal = ZONE_GOALS[c.zone];
        p.plan = ZONE_PAGE_PLAN;
      } else {
        p.goal = c.goal;
        p.plan = c.plan;
      }
      add(p);
    });
  });
})();

